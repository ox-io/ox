use ox_lexer::{lex, CANONICAL_KEYWORDS, RESERVED_KEYWORDS};
use ox_parser::parse;
use ox_types::check;
use std::collections::HashSet;
use std::env;
use std::fs;
use std::process::ExitCode;

fn main() -> ExitCode {
    match run(env::args().skip(1).collect()) {
        Ok(output) => {
            if !output.is_empty() {
                println!("{output}");
            }
            ExitCode::SUCCESS
        }
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

fn run(args: Vec<String>) -> Result<String, String> {
    match args.as_slice() {
        [command] if command == "version" || command == "--version" => {
            Ok(format!("ox {}", env!("CARGO_PKG_VERSION")))
        }
        [command] if command == "keywords" => Ok(format!(
            "Implemented ({}): {}\nReserved ({}): {}",
            CANONICAL_KEYWORDS.len(),
            CANONICAL_KEYWORDS.join(" "),
            RESERVED_KEYWORDS.len(),
            RESERVED_KEYWORDS.join(" ")
        )),
        [command, path] if command == "check" || command == "test" => {
            let source = load_modules(
                std::path::Path::new(path),
                &mut Vec::new(),
                &mut HashSet::new(),
            )?;
            let tokens = lex(&source).map_err(|error| format!("{path}: {error}"))?;
            let program = parse(&tokens).map_err(|error| format!("{path}: {error}"))?;
            check(&program).map_err(|error| format!("{path}: {error}"))?;
            Ok(if command == "test" {
                format!("Tested {path}")
            } else {
                format!("Checked {path}")
            })
        }
        [command] if command == "init" => {
            if std::path::Path::new("ox.toml").exists() {
                return Err("ox.toml already exists".into());
            }
            fs::write(
                "ox.toml",
                "[package]\nname = \"app\"\nversion = \"0.1.0\"\n\n[dependencies]\n",
            )
            .map_err(|e| e.to_string())?;
            Ok("Created ox.toml".into())
        }
        [command] if command == "lock" => lock(false),
        [command, flag] if command == "lock" && flag == "--offline" => lock(true),
        _ => Err("usage: ox <check FILE|test FILE|init|lock|keywords|version>".into()),
    }
}

fn stable_hash(value: &str) -> u64 {
    value.bytes().fold(0xcbf29ce484222325_u64, |state, byte| {
        (state ^ u64::from(byte)).wrapping_mul(0x100000001b3)
    })
}

fn load_modules(
    path: &std::path::Path,
    visiting: &mut Vec<std::path::PathBuf>,
    loaded: &mut HashSet<std::path::PathBuf>,
) -> Result<String, String> {
    let path = path
        .canonicalize()
        .map_err(|e| format!("{}: {e}", path.display()))?;
    if visiting.contains(&path) {
        return Err(format!("module import cycle at {}", path.display()));
    }
    if !loaded.insert(path.clone()) {
        return Ok(String::new());
    }
    visiting.push(path.clone());
    let source = fs::read_to_string(&path).map_err(|e| e.to_string())?;
    let mut dependencies = String::new();
    let mut body = Vec::new();
    let mut aliases = Vec::new();
    for line in source.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("use \"") {
            let end = rest.find('"').ok_or("invalid module import")?;
            if let Some(alias) = rest[end + 1..].trim().strip_prefix("as ") {
                aliases.push(alias.trim_end_matches(';').trim().to_owned());
            }
            dependencies.push_str(&load_modules(
                &path.parent().unwrap().join(&rest[..end]),
                visiting,
                loaded,
            )?);
            dependencies.push('\n');
        } else {
            body.push(line);
        }
    }
    visiting.pop();
    let mut body = body.join("\n");
    for alias in aliases {
        body = body.replace(&format!("{alias}."), "");
    }
    let body = body
        .replace("pub fx ", "fx ")
        .replace("pub shape ", "shape ")
        .replace("pub choice ", "choice ")
        .replace("pub api ", "api ");
    Ok(format!("{dependencies}{body}"))
}

fn lock(offline: bool) -> Result<String, String> {
    let manifest = fs::read_to_string("ox.toml").map_err(|e| format!("ox.toml: {e}"))?;
    let manifest_hash = stable_hash(&manifest);
    let mut output = format!(
        "# Generated by Ox; do not edit.\nversion = 1\nmanifest = \"{manifest_hash:016x}\"\n"
    );
    let dependencies = manifest.split("[dependencies]").nth(1).unwrap_or("");
    fs::create_dir_all(".ox/cache").map_err(|e| e.to_string())?;
    for line in dependencies
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('['))
    {
        let (name, raw) = line
            .split_once('=')
            .ok_or_else(|| format!("invalid dependency: {line}"))?;
        let path = raw.trim().trim_matches('"');
        let cache = format!(".ox/cache/{}.manifest", name.trim());
        let content = if offline {
            fs::read_to_string(&cache)
                .map_err(|_| format!("dependency '{}' is not cached", name.trim()))?
        } else {
            let dependency = fs::read_to_string(std::path::Path::new(path).join("ox.toml"))
                .map_err(|e| format!("dependency '{}': {e}", name.trim()))?;
            fs::write(&cache, &dependency).map_err(|e| e.to_string())?;
            dependency
        };
        output.push_str(&format!(
            "dependency = \"{} {} {:016x}\"\n",
            name.trim(),
            path,
            stable_hash(&content)
        ));
    }
    if offline {
        let existing = fs::read_to_string("ox.lock").map_err(|e| format!("ox.lock: {e}"))?;
        if existing != output {
            return Err("ox.lock is stale".into());
        }
        Ok("Verified offline lock".into())
    } else {
        fs::write("ox.lock", output).map_err(|e| e.to_string())?;
        Ok("Locked dependencies".into())
    }
}
